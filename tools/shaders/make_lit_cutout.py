"""Writes client/Assets/Resources/Shaders/LitCutout.shader from URP's own Lit shader.

Rth/LitCutout is URP Lit unchanged, except that its colour, depth and G-buffer passes first call
RthCutout (OccluderCutout.hlsl): the see-through hole an Occluder opens round the player. Shadows
are left whole. Occluders switch a Lit material to it only while they stand in the way.

Run it again after URP is updated (it reads Lit.shader from client/Library/PackageCache):
    python tools/shaders/make_lit_cutout.py
"""
import glob
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(REPO, "client", "Assets", "Resources", "Shaders", "LitCutout.shader")

found = glob.glob(os.path.join(REPO, "client", "Library", "PackageCache", "com.unity.render-pipelines.universal*", "Shaders", "Lit.shader"))
if not found:
    sys.exit("URP's Lit.shader isn't in client/Library/PackageCache: open the project in Unity once first.")
src = open(found[0], encoding="utf-8").read()

WRAPPERS = {
    "LitPassFragment": """
            #include "OccluderCutout.hlsl"
            void RthLitPassFragment(Varyings input, out half4 outColor : SV_Target0
            #ifdef _WRITE_RENDERING_LAYERS
                , out uint outRenderingLayers : SV_Target1
            #endif
            )
            {
                RthCutout(input.positionCS);
                LitPassFragment(input, outColor
            #ifdef _WRITE_RENDERING_LAYERS
                    , outRenderingLayers
            #endif
                );
            }
""",
    "LitGBufferPassFragment": """
            #include "OccluderCutout.hlsl"
            GBufferFragOutput RthLitGBufferPassFragment(Varyings input)
            {
                RthCutout(input.positionCS);
                return LitGBufferPassFragment(input);
            }
""",
    "DepthOnlyFragment": """
            #include "OccluderCutout.hlsl"
            half RthDepthOnlyFragment(Varyings input) : SV_TARGET
            {
                RthCutout(input.positionCS);
                return DepthOnlyFragment(input);
            }
""",
    "DepthNormalsFragment": """
            #include "OccluderCutout.hlsl"
            void RthDepthNormalsFragment(Varyings input, out half4 outNormalWS : SV_Target0
            #ifdef _WRITE_RENDERING_LAYERS
                , out uint outRenderingLayers : SV_Target1
            #endif
            )
            {
                RthCutout(input.positionCS);
                DepthNormalsFragment(input, outNormalWS
            #ifdef _WRITE_RENDERING_LAYERS
                    , outRenderingLayers
            #endif
                );
            }
""",
}

out = src.replace('Shader "Universal Render Pipeline/Lit"', 'Shader "Rth/LitCutout"', 1)
assert out != src, "Lit.shader's name has changed"

# Each pass is a Pass { ... HLSLPROGRAM ... ENDHLSL } block: wrap the fragments named above.
done = set()
def wrap_pass(match):
    block = match.group(0)
    m = re.search(r"#pragma fragment (\w+)", block)
    if not m or m.group(1) not in WRAPPERS:
        return block
    name = m.group(1)
    done.add(name)
    block = block.replace("#pragma fragment " + name, "#pragma fragment Rth" + name, 1)
    return block.replace("ENDHLSL", WRAPPERS[name].rstrip() + "\n            ENDHLSL", 1)

out = re.sub(r"HLSLPROGRAM.*?ENDHLSL", wrap_pass, out, flags=re.S)
missing = set(WRAPPERS) - done
assert not missing, "passes not found in Lit.shader: " + ", ".join(sorted(missing))

header = ("// GENERATED by tools/shaders/make_lit_cutout.py from URP's Lit.shader: do not edit by hand.\n"
          "// URP Lit with the occluder's see-through hole (OccluderCutout.hlsl) in its colour, depth and\n"
          "// G-buffer passes; shadows stay whole.\n")
open(OUT, "w", encoding="utf-8", newline="\n").write(header + out)
print("wrote", OUT, "wrapped:", ", ".join(sorted(done)))
