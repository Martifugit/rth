        private const float Storey = 2.6f;

        // ------------------------------------------------------------------ asset tags

        /// <summary>Tags a placed group as the stand-in for an asset (see <see cref="BlockoutAsset"/>).</summary>
        public static Transform Asset(Transform t, string id, string note)
        {
            BlockoutAsset tag = t.GetComponent<BlockoutAsset>();
            if (tag == null) tag = t.gameObject.AddComponent<BlockoutAsset>();
            tag.id = id;
            tag.note = note;
            return t;
        }

        /// <summary>
        /// Writes docs/regions/&lt;region&gt;-assets.md: every tagged asset in the region, how many
        /// there are, roughly how big (the largest copy), and its note. Run by <see cref="SaveRegion"/>.
        /// </summary>
        public static string WriteAssetList(MapArea area)
        {
            var groups = area.GetComponentsInChildren<BlockoutAsset>()
                .Where(a => !string.IsNullOrWhiteSpace(a.id))
                .GroupBy(a => a.id.Trim())
                .OrderBy(g => g.Key)
                .ToList();
            if (groups.Count == 0) return null;
            var sb = new StringBuilder();
            sb.Append("# ").Append(string.IsNullOrWhiteSpace(area.title) ? area.exportName : area.title).Append(": assets to make\n\n");
            sb.Append("Generated by the region's builder when it saves (`WorldKit.WriteAssetList`): every piece of the\n");
            sb.Append("blockout that stands in for an asset, with how many are placed and the size of the largest copy\n");
            sb.Append("in metres (1 tile = 1 m), width x depth x height. Don't edit by hand; change the builder's notes.\n\n");
            sb.Append("| Asset | Count | Size (m) | Notes |\n|---|---|---|---|\n");
            foreach (IGrouping<string, BlockoutAsset> g in groups)
            {
                Vector3 size = Vector3.zero;
                foreach (BlockoutAsset a in g)
                {
                    Bounds? b = BoundsOf(a.transform);
                    if (b.HasValue && b.Value.size.sqrMagnitude > size.sqrMagnitude) size = b.Value.size;
                }
                string note = g.Select(a => a.note).FirstOrDefault(n => !string.IsNullOrWhiteSpace(n)) ?? "";
                sb.Append("| `").Append(g.Key).Append("` | ").Append(g.Count()).Append(" | ")
                  .Append(size.x.ToString("0.#")).Append(" x ").Append(size.z.ToString("0.#")).Append(" x ").Append(size.y.ToString("0.#"))
                  .Append(" | ").Append(note.Replace("\n", " ").Replace("|", "/")).Append(" |\n");
            }
            string dir = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "..", "docs", "regions"));
            Directory.CreateDirectory(dir);
            string path = Path.Combine(dir, area.exportName + "-assets.md");
            File.WriteAllText(path, sb.ToString());
            return path;
        }

        private static Bounds? BoundsOf(Transform t)
        {
            Bounds? all = null;
            foreach (Renderer r in t.GetComponentsInChildren<Renderer>())
            {
                if (r is ParticleSystemRenderer) continue;
                if (all == null) all = r.bounds;
                else
                {
                    Bounds b = all.Value;
                    b.Encapsulate(r.bounds);
                    all = b;
                }
            }
            return all;
        }

        // ------------------------------------------------------------------ small helpers

        /// <summary>A box with no collider (most of a blockout is only to be looked at).</summary>
        public static GameObject Prop(string name, Transform parent, Vector3 center, Vector3 size, Material material, float yaw = 0f) =>
            Box(name, parent, center, size, material, collider: false, yaw: yaw);

        /// <summary>A box lying along the line from a to b (a beam, a rope, an arm), with the given cross-section.</summary>
        public static GameObject Beam(string name, Transform parent, Vector3 a, Vector3 b, float width, float height, Material material)
        {
            GameObject go = Prop(name, parent, (a + b) / 2f, new Vector3(width, height, Vector3.Distance(a, b)), material);
            if ((b - a).sqrMagnitude > 0.0001f) go.transform.rotation = Quaternion.LookRotation(b - a);
            return go;
        }

        /// <summary>Blocks the tiles under a group's footprint without drawing anything (furniture you can't walk through).</summary>
        public static void BlockTiles(Transform parent, string name, int x0, int z0, int x1, int z1)
        {
            GameObject go = Box(name, parent, new Vector3((x0 + x1) / 2f, 0.3f, (z0 + z1) / 2f), new Vector3(x1 - x0 - 0.1f, 0.6f, z1 - z0 - 0.1f), null);
            Object.DestroyImmediate(go.GetComponent<Renderer>());
            Object.DestroyImmediate(go.GetComponent<MeshFilter>());
            go.AddComponent<MapBlocker>();
        }

        /// <summary>Water nobody will ever reach, beyond the region's edge (the sea carrying on into the fog). No collider.</summary>
        public static void FarWater(Transform parent, string name, Rect area, Material water)
        {
            Prop(name, parent, new Vector3(area.center.x, -0.05f, area.center.y), new Vector3(area.width, 0.05f, area.height), water)
                .GetComponent<Renderer>().shadowCastingMode = ShadowCastingMode.Off;
        }

        // ------------------------------------------------------------------ roofs

        public enum RoofKind
        {
            /// <summary>Two slopes meeting at a ridge along the longer side, with filled gable ends.</summary>
            Gable,
            /// <summary>A flat top behind a parapet (warehouses, towers you could stand on).</summary>
            Flat,
            /// <summary>A flat top behind battlements.</summary>
            Battlements,
            /// <summary>A stepped spire (towers, belfries).</summary>
            Spire,
            /// <summary>A stepped dome on a short drum (vaults, shrines, southern houses).</summary>
            Dome,
            /// <summary>No roof (a ruin, or something with its own).</summary>
            None,
        }

        /// <summary>
        /// A gabled roof over tiles [x0,x1) x [z0,z1) whose eaves sit at <paramref name="eave"/>,
        /// ridge along the longer side, overhanging a little, with triangular gables filling the
        /// ends. Also makes tents (eave 0). Returns the roof group.
        /// </summary>
        public static Transform GableRoof(Transform parent, float x0, float z0, float x1, float z1, float eave, Material roof, Material gable,
            float pitch = 38f, float overhang = 0.3f)
        {
            Transform group = Group(parent, "Roof");
            bool alongX = x1 - x0 >= z1 - z0;
            float tan = Mathf.Tan(pitch * Mathf.Deg2Rad);
            float length = (alongX ? x1 - x0 : z1 - z0) + 2f * overhang;
            float half = (alongX ? z1 - z0 : x1 - x0) / 2f + overhang;
            float slab = half / Mathf.Cos(pitch * Mathf.Deg2Rad);
            float rise = half * tan;
            var c = new Vector3((x0 + x1) / 2f, eave, (z0 + z1) / 2f);
            for (int s = -1; s <= 1; s += 2)
            {
                Vector3 offset = alongX ? new Vector3(0f, rise / 2f, s * half / 2f) : new Vector3(s * half / 2f, rise / 2f, 0f);
                GameObject side = Prop("Slope", group, c + offset, alongX ? new Vector3(length, 0.14f, slab) : new Vector3(slab, 0.14f, length), roof);
                // Each slope tilts so its outer edge is low and its ridge edge high.
                side.transform.rotation = alongX ? Quaternion.Euler(s * pitch, 0f, 0f) : Quaternion.Euler(0f, 0f, -s * pitch);
            }
            Prop("Ridge", group, c + new Vector3(0f, rise + 0.02f, 0f), alongX ? new Vector3(length, 0.16f, 0.22f) : new Vector3(0.22f, 0.16f, length), roof);

            // The gables: a diamond squashed to the roof's pitch, its lower half hidden in the walls.
            if (gable != null)
            {
                float gHalf = (alongX ? z1 - z0 : x1 - x0) / 2f;
                foreach (float end in alongX ? new[] { x0 + 0.05f, x1 - 0.05f } : new[] { z0 + 0.05f, z1 - 0.05f })
                {
                    var holder = new GameObject("Gable");
                    holder.transform.SetParent(group, false);
                    holder.transform.position = alongX ? new Vector3(end, eave, c.z) : new Vector3(c.x, eave, end);
                    holder.transform.localScale = new Vector3(1f, tan, 1f);
                    GameObject diamond = Prop("Gable", holder.transform, holder.transform.position, Vector3.one, gable);
                    diamond.transform.localPosition = Vector3.zero;
                    diamond.transform.localRotation = alongX ? Quaternion.Euler(45f, 0f, 0f) : Quaternion.Euler(0f, 0f, 45f);
                    float d = gHalf * Mathf.Sqrt(2f);
                    diamond.transform.localScale = alongX ? new Vector3(0.12f, d, d) : new Vector3(d, d, 0.12f);
                }
            }
            return group;
        }

        /// <summary>Merlons along a line at a height: the toothed top of a wall or tower.</summary>
        public static void Battlements(Transform parent, Vector3 from, Vector3 to, Material stone, float merlon = 0.55f, float height = 0.6f, float thickness = 0.35f)
        {
            float length = Vector3.Distance(from, to);
            int count = Mathf.Max(1, Mathf.RoundToInt(length / (merlon * 2f)));
            Vector3 dir = (to - from).normalized;
            float yaw = Mathf.Atan2(dir.x, dir.z) * Mathf.Rad2Deg;
            for (int i = 0; i < count; i++)
            {
                Vector3 at = Vector3.Lerp(from, to, (i + 0.5f) / count) + Vector3.up * (height / 2f);
                Prop("Merlon", parent, at, new Vector3(thickness, height, merlon), stone, yaw);
            }
        }

        /// <summary>A stepped spire: shrinking tiers, each a little taller than wide, ending in a finial.</summary>
        public static Transform Spire(Transform parent, Vector3 baseCenter, float width, float height, Material roof, Material finial = null, int tiers = 6)
        {
            Transform group = Group(parent, "Spire");
            float y = baseCenter.y;
            float step = height / tiers;
            for (int i = 0; i < tiers; i++)
            {
                float w = width * (1f - i / (float)tiers) * 0.95f + 0.1f;
                Prop("Tier", group, new Vector3(baseCenter.x, y + step / 2f, baseCenter.z), new Vector3(w, step, w), roof, 45f * (i % 2) * 0.25f);
                y += step;
            }
            if (finial != null)
            {
                Prop("Finial", group, new Vector3(baseCenter.x, y + 0.4f, baseCenter.z), new Vector3(0.1f, 0.8f, 0.1f), finial);
                Prop("Finial cross", group, new Vector3(baseCenter.x, y + 0.6f, baseCenter.z), new Vector3(0.4f, 0.1f, 0.1f), finial);
            }
            return group;
        }

