        /// <summary>How a building's walls are dressed.</summary>
        public sealed class Facade
        {
            public Material Walls;
            public Material Roof;
            /// <summary>Gable ends; null for none.</summary>
            public Material Gable;
            /// <summary>Bands between storeys and the plinth; null for none.</summary>
            public Material Trim;
            /// <summary>Window openings (dark or lit glass); null for none.</summary>
            public Material Windows;
            public float Pitch = 40f;
        }

        /// <summary>
        /// A building nobody goes into: it blocks its tiles [x0,x1) x [z0,z1), rises to
        /// <paramref name="eave"/>, and is dressed with storey bands, rows of windows on every face
        /// and a roof. It fades when it hides the player. Returns the building's group (tag it).
        /// </summary>
        public static Transform Building(Transform parent, string name, int x0, int z0, int x1, int z1, float eave, Facade f, RoofKind roof = RoofKind.Gable)
        {
            Transform b = Group(parent, name);
            Box("Body", b, new Vector3((x0 + x1) / 2f, eave / 2f, (z0 + z1) / 2f), new Vector3(x1 - x0 - 0.1f, eave, z1 - z0 - 0.1f), f.Walls)
                .AddComponent<MapBlocker>();
            int storeys = Mathf.Max(1, Mathf.FloorToInt(eave / Storey));
            if (f.Trim != null)
            {
                Prop("Plinth", b, new Vector3((x0 + x1) / 2f, 0.2f, (z0 + z1) / 2f), new Vector3(x1 - x0 + 0.06f, 0.4f, z1 - z0 + 0.06f), f.Trim);
                for (int s = 1; s < storeys; s++)
                    Prop("Band", b, new Vector3((x0 + x1) / 2f, s * Storey, (z0 + z1) / 2f), new Vector3(x1 - x0 + 0.04f, 0.14f, z1 - z0 + 0.04f), f.Trim);
            }
            if (f.Windows != null) Windows(b, x0, z0, x1, z1, storeys, f.Windows);
            Roof(b, x0, z0, x1, z1, eave, f, roof);
            Fades(b, 0.3f);
            return b;
        }

        private static void Windows(Transform b, int x0, int z0, int x1, int z1, int storeys, Material glass)
        {
            for (int s = 0; s < storeys; s++)
            {
                float y = s * Storey + (s == 0 ? 1.3f : 1.45f);
                for (float x = x0 + 1f; x <= x1 - 1f + 0.01f; x += 1.6f)
                {
                    Prop("Window", b, new Vector3(x, y, z0 - 0.02f), new Vector3(0.5f, 0.85f, 0.08f), glass);
                    Prop("Window", b, new Vector3(x, y, z1 + 0.02f), new Vector3(0.5f, 0.85f, 0.08f), glass);
                }
                for (float z = z0 + 1f; z <= z1 - 1f + 0.01f; z += 1.6f)
                {
                    Prop("Window", b, new Vector3(x0 - 0.02f, y, z), new Vector3(0.08f, 0.85f, 0.5f), glass);
                    Prop("Window", b, new Vector3(x1 + 0.02f, y, z), new Vector3(0.08f, 0.85f, 0.5f), glass);
                }
            }
        }

        private static void Roof(Transform b, float x0, float z0, float x1, float z1, float eave, Facade f, RoofKind kind)
        {
            switch (kind)
            {
                case RoofKind.Gable:
                    GableRoof(b, x0, z0, x1, z1, eave, f.Roof, f.Gable ?? f.Walls, f.Pitch);
                    break;
                case RoofKind.Flat:
                    Prop("Roof", b, new Vector3((x0 + x1) / 2f, eave + 0.05f, (z0 + z1) / 2f), new Vector3(x1 - x0 + 0.1f, 0.1f, z1 - z0 + 0.1f), f.Roof);
                    foreach ((Vector3 a, Vector3 c) in Edges(x0, z0, x1, z1, eave))
                        Beam("Parapet", b, a + Vector3.up * 0.3f, c + Vector3.up * 0.3f, 0.25f, 0.6f, f.Trim ?? f.Walls);
                    break;
                case RoofKind.Battlements:
                    Prop("Roof", b, new Vector3((x0 + x1) / 2f, eave + 0.05f, (z0 + z1) / 2f), new Vector3(x1 - x0 + 0.1f, 0.1f, z1 - z0 + 0.1f), f.Roof);
                    foreach ((Vector3 a, Vector3 c) in Edges(x0, z0, x1, z1, eave))
                        Battlements(b, a, c, f.Trim ?? f.Walls);
                    break;
                case RoofKind.Spire:
                    Spire(b, new Vector3((x0 + x1) / 2f, eave, (z0 + z1) / 2f), Mathf.Min(x1 - x0, z1 - z0) + 0.3f, Mathf.Min(x1 - x0, z1 - z0) * 2.2f, f.Roof, f.Trim);
                    break;
                case RoofKind.Dome:
                    Prop("Roof", b, new Vector3((x0 + x1) / 2f, eave + 0.05f, (z0 + z1) / 2f), new Vector3(x1 - x0 + 0.1f, 0.1f, z1 - z0 + 0.1f), f.Trim ?? f.Walls);
                    Dome(b, new Vector3((x0 + x1) / 2f, eave, (z0 + z1) / 2f), Mathf.Min(x1 - x0, z1 - z0) * 0.42f, Mathf.Min(x1 - x0, z1 - z0) * 0.4f, f.Roof, f.Trim);
                    break;
            }
        }

        /// <summary>The four top edges of a footprint, just inside it.</summary>
        private static IEnumerable<(Vector3, Vector3)> Edges(float x0, float z0, float x1, float z1, float y)
        {
            const float i = 0.15f;
            yield return (new Vector3(x0 + i, y, z0 + i), new Vector3(x1 - i, y, z0 + i));
            yield return (new Vector3(x0 + i, y, z1 - i), new Vector3(x1 - i, y, z1 - i));
            yield return (new Vector3(x0 + i, y, z0 + i), new Vector3(x0 + i, y, z1 - i));
            yield return (new Vector3(x1 - i, y, z0 + i), new Vector3(x1 - i, y, z1 - i));
        }

        /// <summary>A door in a hall: which wall, and the tiles of the opening along it.</summary>
        public struct Door
        {
            public Side Side;
            public int From;
            public int To;

            public Door(Side side, int from, int to)
            {
                Side = side;
                From = from;
                To = to;
            }

            public Door(Side side, int at) : this(side, at, at)
            {
            }
        }

        /// <summary>
        /// A building you can walk into, of any size: a floor, walls of the given height with door
        /// openings (blocking edges like <see cref="House"/>'s), and a gabled roof that hides while
        /// you're inside. Interior furniture is the builder's. Returns the hall's group.
        /// </summary>
        public static Transform Hall(Transform parent, string name, int x0, int z0, int x1, int z1, float height, Facade f, Material floor, params Door[] doors)
        {
            Transform hall = Group(parent, name);
            Patch("Floor", hall, x0, z0, x1, z1, floor, 0.02f);
            Transform walls = Group(hall, "Walls");
            // Walls stay 0.2 thick: any thicker and the exporter would block the next tile's edge too, closing the doors.
            int[] GapsOn(Side side) => doors.Where(d => d.Side == side).SelectMany(d => Enumerable.Range(d.From, d.To - d.From + 1)).ToArray();
            Wall(walls, "Wall S", x0, z0, x1, z0, f.Walls, height, 0.2f, GapsOn(Side.South));
            Wall(walls, "Wall N", x0, z1, x1, z1, f.Walls, height, 0.2f, GapsOn(Side.North));
            Wall(walls, "Wall W", x0, z0, x0, z1, f.Walls, height, 0.2f, GapsOn(Side.West));
            Wall(walls, "Wall E", x1, z0, x1, z1, f.Walls, height, 0.2f, GapsOn(Side.East));
            // Lintels over the doors, so an opening reads as a doorway and not a missing wall.
            foreach (Door d in doors)
            {
                bool alongX = d.Side == Side.South || d.Side == Side.North;
                float line = d.Side == Side.South ? z0 : d.Side == Side.North ? z1 : d.Side == Side.West ? x0 : x1;
                float mid = (d.From + d.To + 1) / 2f;
                float span = d.To - d.From + 1;
                float doorTop = Mathf.Min(height - 0.3f, 2.4f + span * 0.4f);
                Prop("Lintel", walls, alongX ? new Vector3(mid, (doorTop + height) / 2f, line) : new Vector3(line, (doorTop + height) / 2f, mid),
                    alongX ? new Vector3(span, height - doorTop, 0.3f) : new Vector3(0.3f, height - doorTop, span), f.Walls);
            }
            // The cornice is a ring round the wall tops, not a slab: a lid would hide the interior when the roof does.
            if (f.Trim != null)
                foreach ((Vector3 a, Vector3 c) in Edges(x0 - 0.1f, z0 - 0.1f, x1 + 0.1f, z1 + 0.1f, height))
                    Beam("Cornice", walls, a, c, 0.45f, 0.2f, f.Trim);
            Fades(walls, 0.3f);

            Transform roof = GableRoof(hall, x0, z0, x1, z1, height, f.Roof, f.Gable ?? f.Walls, f.Pitch);
            Fades(roof, 0.15f);
            roof.gameObject.AddComponent<RoofHider>().interior = new RectInt(x0, z0, x1 - x0, z1 - z0);
            return hall;
        }

