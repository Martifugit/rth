        /// A stone bridge deck over tiles [x0,x1) x [z0,z1) (keep them out of the water so they can
        /// be walked), crossing along X or Z, with parapets on both sides and arches under it.
        /// </summary>
        public static Transform StoneBridge(Transform parent, string name, int x0, int z0, int x1, int z1, bool alongX, Material deck, Material stone, int arches = 2)
        {
