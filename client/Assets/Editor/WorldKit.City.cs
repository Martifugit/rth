        /// <summary>
        /// A city wall one tile thick along a row or column of tiles, from (x0,z0) up to but not
        /// including (x1,z1), leaving open the tiles in <paramref name="gaps"/> (counted along the
        /// line). Its tiles are blocked; a wall-walk with battlements on both sides runs along the top.
        /// </summary>
        public static Transform CityWall(Transform parent, string name, int x0, int z0, int x1, int z1, float height, Material stone, Material walk, params int[] gaps)
        {
            Transform group = Group(parent, name);
            bool alongX = z0 == z1;
            int from = alongX ? Mathf.Min(x0, x1) : Mathf.Min(z0, z1);
            int to = alongX ? Mathf.Max(x0, x1) : Mathf.Max(z0, z1);
            var gapSet = new HashSet<int>(gaps);
            int runStart = from;
            for (int t = from; t <= to; t++)
            {
                if (t != to && !gapSet.Contains(t)) continue;
                if (t > runStart)
                {
                    float a = runStart, b = t, line = alongX ? z0 + 0.5f : x0 + 0.5f;
                    Vector3 center = alongX ? new Vector3((a + b) / 2f, height / 2f, line) : new Vector3(line, height / 2f, (a + b) / 2f);
                    Vector3 size = alongX ? new Vector3(b - a, height, 0.96f) : new Vector3(0.96f, height, b - a);
                    Box("Wall", group, center, size, stone).AddComponent<MapBlocker>();
                    Prop("Wall-walk", group, center + Vector3.up * (height / 2f + 0.03f), alongX ? new Vector3(b - a, 0.06f, 0.9f) : new Vector3(0.9f, 0.06f, b - a), walk);
                    Prop("Footing", group, new Vector3(center.x, 0.3f, center.z), alongX ? new Vector3(b - a, 0.6f, 1.3f) : new Vector3(1.3f, 0.6f, b - a), stone);
                    for (int s = -1; s <= 1; s += 2)
                    {
                        Vector3 off = alongX ? new Vector3(0f, height / 2f, s * 0.42f) : new Vector3(s * 0.42f, height / 2f, 0f);
                        Vector3 ra = alongX ? new Vector3(a, 0f, 0f) : new Vector3(0f, 0f, a);
                        Vector3 rb = alongX ? new Vector3(b, 0f, 0f) : new Vector3(0f, 0f, b);
                        Vector3 baseLine = alongX ? new Vector3(0f, 0f, line) : new Vector3(line, 0f, 0f);
                        Battlements(group, baseLine + ra + off, baseLine + rb + off, stone, 0.5f, 0.6f, 0.2f);
                    }
                }
                runStart = t + 1;
            }
            Fades(group, 0.3f);
            return group;
        }

        /// <summary>
        /// A tower on a square of tiles (blocked), with arrow slits, a string course and a top:
        /// battlements, a stepped spire or a flat roof. Returns its group.
        /// </summary>
        public static Transform Tower(Transform parent, string name, int x, int z, int size, float height, Material stone, Material top, Material slits, RoofKind roof = RoofKind.Battlements, Material trim = null)
        {
            Transform t = Group(parent, name);
            var c = new Vector3(x + size / 2f, 0f, z + size / 2f);
            Box("Body", t, c + Vector3.up * (height / 2f), new Vector3(size - 0.04f, height, size - 0.04f), stone).AddComponent<MapBlocker>();
            Prop("Batter", t, c + Vector3.up * 0.5f, new Vector3(size + 0.4f, 1f, size + 0.4f), trim ?? stone);
            Prop("Corbels", t, c + Vector3.up * (height - 0.25f), new Vector3(size + 0.35f, 0.5f, size + 0.35f), trim ?? stone);
            if (slits != null)
                for (float y = 3f; y < height - 1.5f; y += 3.2f)
                    for (int s = 0; s < 4; s++)
                    {
                        Vector3 face = Quaternion.Euler(0f, s * 90f, 0f) * new Vector3(0f, 0f, size / 2f + 0.03f);
                        Prop("Slit", t, c + face + Vector3.up * y, s % 2 == 0 ? new Vector3(0.22f, 0.9f, 0.08f) : new Vector3(0.08f, 0.9f, 0.22f), slits);
                    }
            var f = new Facade { Walls = stone, Roof = top, Trim = trim ?? stone };
