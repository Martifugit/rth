    /// <summary>
    /// The pieces cities are blocked out with: buildings you can't enter (they block their tiles)
    /// with gabled or flat roofs, storey bands and windows; halls you can (walls with doors and a
    /// roof that hides inside); city walls, towers, spires, gates and arches; stone bridges;
    /// statues, braziers, banners, stalls, tents, boats, cranes and other street furniture.
    /// Everything that stands in for an asset still to be made is tagged with
    /// <see cref="Asset"/>, and <see cref="SaveRegion"/> writes the region's asset list.
    /// Coordinates are tiles, as in the rest of the kit: (x, z) is the tile's south-west corner.
