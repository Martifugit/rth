        /// <summary>
        /// An arch from <paramref name="a"/> to <paramref name="b"/> (its two springing points on
        /// the ground line), rising to <paramref name="crown"/> above the springing height: a ring
        /// of stones with a solid spandrel to <paramref name="top"/>. Scenery only.
        /// </summary>
        public static Transform Arch(Transform parent, Vector3 a, Vector3 b, float spring, float crown, float top, float thickness, Material stone, int stones = 9)
        {
            Transform group = Group(parent, "Arch");
            Vector3 mid = (a + b) / 2f;
            Vector3 dir = (b - a).normalized;
            float r = Vector3.Distance(a, b) / 2f;
            float yaw = Mathf.Atan2(dir.x, dir.z) * Mathf.Rad2Deg;
            for (int i = 0; i < stones; i++)
            {
                float t0 = i / (float)stones * Mathf.PI, t1 = (i + 1) / (float)stones * Mathf.PI;
                Vector3 p0 = mid - dir * (Mathf.Cos(t0) * r) + Vector3.up * (spring + Mathf.Sin(t0) * crown);
                Vector3 p1 = mid - dir * (Mathf.Cos(t1) * r) + Vector3.up * (spring + Mathf.Sin(t1) * crown);
                GameObject v = Beam("Voussoir", group, p0, p1, thickness, 0.45f, stone);
                v.transform.localScale = new Vector3(thickness, 0.45f, Vector3.Distance(p0, p1) + 0.12f);
            }
            // The spandrel: solid wall over the arch up to the top, in strips that follow its curve.
            const int strips = 4;
            for (int i = 0; i < strips; i++)
            {
                float outer = r * (1f - i / (float)strips), inner = r * (1f - (i + 1f) / strips);
                float x = (outer + inner) / 2f; // distance from the middle
                float bottom = spring + crown * Mathf.Sqrt(Mathf.Max(0f, 1f - x * x / (r * r)));
                if (top <= bottom) continue;
                foreach (int s in new[] { -1, 1 })
                {
                    Vector3 at = mid + dir * (s * x);
                    Prop("Spandrel", group, new Vector3(at.x, (bottom + top) / 2f, at.z), new Vector3(thickness, top - bottom, outer - inner + 0.02f), stone, yaw);
                }
            }
            if (top > spring + crown)
                Prop("Over the crown", group, new Vector3(mid.x, (spring + crown + top) / 2f, mid.z), new Vector3(thickness, top - spring - crown, r * 0.5f + 0.02f), stone, yaw);
            return group;
        }

